using System.Collections.Generic;
using System.Linq;
using TMPro;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.Events;
using UnityEngine.InputSystem;
using UnityEngine.InputSystem.UI;
using UnityEngine.SceneManagement;
using UnityEngine.UI;
using Draftmaster.Controls;
using Draftmaster.Data;
using Draftmaster.Fans;
using Draftmaster.Sponsors;
// GarageUI declares a `Series` of its own in the global namespace, which would shadow the database model.
using SeriesInfo = Draftmaster.Data.Series;

// The garage screen, built to the Iron Oval design file's GARAGE pass: the car and driver identity down the
// left with career and accolades under it, the driver's own stats in the middle over an XP meter, and their
// traits over their relationship with the player on the right.
//
// The sheet is a JRPG character sheet, so the job here is binding each field to something the game really
// keeps rather than inventing an RPG:
//
//   PERSONAL      the player's row in the Drivers table, found the way the rest of the game finds it —
//                 by the number on the car (PlayerDriver). Name and age come straight off that row; the
//                 number and the team are already on the car above it.
//   DRIVER STATS  every attribute that row carries: both 0-100 ability ratings and all sixteen 0-20
//                 skills, laid out by DriverAttributeSheet. No row at all = the block reads as unrated
//                 rather than showing zeros.
//   XP            fan appeal 0-100, the progress meter this game actually has.
//   CAR           the paint the viewed car races in: the player's own scheme and sponsor decals
//                 (PaintShop.RenderPlayerCar), a rival's livery from their championship's carset.
//   CAREER        the player's PlayerStatsLedger counters (starts / wins / top 10s); a real driver's real
//                 career in the series being browsed (SeriesCareers — one record per driver per series, so
//                 a Cup regular's Xfinity starts show under Xfinity).
//   ACCOLADES     derived from those same numbers, so a line only appears once it's been earned.
//   TRAITS        what the driver is known for (DriverTraits), authored per driver; none reads as such.
//   RELATIONSHIP  the rivalry score between this driver and the player (DriverRelationships): its standing,
//                 the number and a line on what it means. The player's own sheet has nobody to relate to,
//                 so it reads N/A.
//
// The top bar carries two dropdowns — the series, and the field entered in it — so the sheet can be read
// for anyone on the grid, not just the player. Where a block is only true of the player (their career
// counters, their accolades, their fan appeal) it says so plainly rather
// than showing the player's numbers under a rival's name: SeriesRoster answers who races where, and
// nothing on this screen writes anything back.
//
// The sheet's bottom strip (a team-roster switcher in the design) is gone: this game has one car, and the
// screen reads as a laptop window — the only way out is the red X in the top bar, back to wherever the
// laptop was opened.
//
// How the player gets here: the laptop in the RV or the one in the team factory, not a row on the title
// menu — see GarageScreenLoader, which also remembers which of those to send BACK to.
//
// Layout is generated by Draftmaster > Art > Build Garage Screen Scene; this only fills it in.
public class GarageScreenUI : MonoBehaviour
{
    [Header("Wired by the builder")]
    [Tooltip("Top-bar series picker. Changing it refills the driver picker with that series' entry list.")]
    public TMP_Dropdown seriesDropdown;
    [Tooltip("Top-bar driver picker: the selected series' field, by car number. Changing it redraws the sheet.")]
    public TMP_Dropdown driverDropdown;
    [Tooltip("The car slot's picture: the viewed driver's car, drawn at a whole-pixel scale that fits the slot.")]
    public Image carImage;
    [Tooltip("Shown in the car slot when there is no paint to draw.")]
    public TextMeshProUGUI carSlotCaption;
    [Tooltip("Personal: the Name value. Shortened to initial and surname, then surname, when the full name does not fit.")]
    public TextMeshProUGUI driverName;
    [Tooltip("Personal: the Age value, off the driver's Drivers row.")]
    public TextMeshProUGUI driverAge;
    [Tooltip("On the Driver Stats heading's line: how much of a rival's sheet has been scouted.")]
    public TextMeshProUGUI scoutingLabel;

    [Tooltip("One row per DriverAttributeSheet.All entry, in that order: label, cells, value.")]
    public List<StatRow> driverStats = new();
    [Tooltip("Three career rows: label, value.")]
    public List<TextPair> careerRows = new();
    [Tooltip("Accolade lines, filled top-down.")]
    public List<TextMeshProUGUI> accoladeLines = new();
    [Tooltip("Trait lines, filled top-down.")]
    public List<TextMeshProUGUI> traitLines = new();
    [Tooltip("Two relationship rows (standing, score): label, value.")]
    public List<TextPair> relationshipRows = new();
    [Tooltip("What the relationship means, or N/A on the player's own sheet.")]
    public TextMeshProUGUI relationshipNote;

    public RectTransform xpBar;
    public TextMeshProUGUI xpLabel;

    [Header("Flow")]
    [Tooltip("Where BACK goes when the sheet was opened cold rather than from a laptop in the RV or the factory.")]
    public string titleSceneName = GarageScreenLoader.TitleSceneName;

    [System.Serializable]
    public class StatRow
    {
        public TextMeshProUGUI label;
        public RectTransform cells;
        public TextMeshProUGUI value;
        [Tooltip("Cell colour. Gold for the driver's stats, as the sheet has it.")]
        public Color tint = new Color(0.91f, 0.69f, 0.24f, 1f);
    }

    [System.Serializable]
    public class TextPair
    {
        public TextMeshProUGUI label;
        public TextMeshProUGUI value;
    }


    // What the top bar is currently pointed at.
    List<SeriesInfo> _series = new();
    List<Driver> _field = new();
    // The championship the field was drawn from, which decides which carset a rival's paint comes out of.
    SeriesInfo _fieldSeries;
    Driver _viewed;
    // False until the pickers have been filled — a sheet built before they existed still shows the
    // player rather than an empty column.
    bool _browsing;
    // Set while options are being rebuilt, so SetValue's own callback can't re-enter and rebuild again.
    bool _populating;

    void Start()
    {
        IronOvalScanlines.Ensure();
        if (EventSystem.current == null)
            new GameObject("EventSystem", typeof(EventSystem), typeof(InputSystemUIInputModule));
        WireButtons();
        BuildPickers();
        Refresh();
    }

    // The close X, hooked up here for the same reason the pickers are: the builder that generates this
    // scene calls onClick.AddListener at edit time, which adds a RUNTIME listener and is thrown away when
    // the scene is saved. The button in the saved scene therefore has an empty onClick, and the only
    // wiring that survives is the wiring done in code, on the way up.
    //
    // Found by the name the builder gives it rather than by a serialized reference, so a rebuilt scene
    // needs no re-dragging.
    void WireButtons()
    {
        Wire("Close", Back);
    }

    void Wire(string objectName, UnityAction action)
    {
        var owner = FindDescendant(transform, objectName);
        if (owner == null)
        {
            Debug.LogWarning($"GarageScreenUI: no '{objectName}' button in the scene — rebuild it with " +
                             "Draftmaster > Art > Build Garage Screen Scene.");
            return;
        }

        var button = owner.GetComponentInChildren<Button>(true);
        if (button == null)
        {
            Debug.LogWarning($"GarageScreenUI: '{objectName}' has no Button, so it can't be pressed.");
            return;
        }

        button.onClick.RemoveListener(action);   // a rebuild in the same session must not double it up
        button.onClick.AddListener(action);
    }

    static Transform FindDescendant(Transform root, string objectName)
    {
        if (root.name == objectName) return root;
        foreach (Transform child in root)
        {
            var found = FindDescendant(child, objectName);
            if (found != null) return found;
        }
        return null;
    }

    // ------------------------------------------------------------------ top bar

    // Fill both dropdowns and open the sheet on the player: their series, their car. Listeners are added
    // here rather than baked into the scene — a UnityEvent wired at build time isn't serialised, so the
    // only wiring that survives a scene save is the wiring done in code.
    public void BuildPickers()
    {
        _series = SeriesRoster.AllSeries();
        int seriesIndex = SeriesRoster.SeriesIndexFor(_series, PlayerDriver.CarNumber);

        if (seriesDropdown != null)
        {
            _populating = true;
            seriesDropdown.ClearOptions();
            seriesDropdown.AddOptions(_series.Select(s => SeriesRoster.Label(s)).ToList());
            seriesDropdown.SetValueWithoutNotify(Mathf.Max(0, seriesIndex));
            seriesDropdown.RefreshShownValue();
            seriesDropdown.onValueChanged.RemoveListener(OnSeriesPicked);
            seriesDropdown.onValueChanged.AddListener(OnSeriesPicked);
            _populating = false;
            _browsing = true;
        }

        if (driverDropdown != null)
        {
            driverDropdown.onValueChanged.RemoveListener(OnDriverPicked);
            driverDropdown.onValueChanged.AddListener(OnDriverPicked);
            _browsing = true;
        }

        KeepArrowsForStepping(seriesDropdown);
        KeepArrowsForStepping(driverDropdown);

        ShowField(seriesIndex, PlayerDriver.CarNumber);
    }

    // The entry list for one series, with the sheet landing on `preferredCarNumber` when that car is in
    // it. A series nobody has been entered into yet says so instead of borrowing another series' field.
    void ShowField(int seriesIndex, int preferredCarNumber)
    {
        var series = seriesIndex >= 0 && seriesIndex < _series.Count ? _series[seriesIndex] : null;
        _fieldSeries = series;
        _field = SeriesRoster.Drivers(series);
        int driverIndex = SeriesRoster.DriverIndexFor(_field, preferredCarNumber);
        _viewed = driverIndex >= 0 && driverIndex < _field.Count ? _field[driverIndex] : null;

        if (driverDropdown == null) return;

        _populating = true;
        driverDropdown.ClearOptions();
        driverDropdown.AddOptions(_field.Count > 0
            ? _field.Select(d => SeriesRoster.Label(d)).ToList()
            : new List<string> { "NO ENTRY LIST YET" });
        driverDropdown.SetValueWithoutNotify(Mathf.Max(0, driverIndex));
        driverDropdown.RefreshShownValue();
        driverDropdown.interactable = _field.Count > 1;
        _populating = false;
    }

    public void OnSeriesPicked(int index)
    {
        if (_populating) return;
        ShowField(index, PlayerDriver.CarNumber);
        Refresh();
    }

    public void OnDriverPicked(int index)
    {
        if (_populating) return;
        _viewed = index >= 0 && index < _field.Count ? _field[index] : null;
        Refresh();
    }

    // The driver the sheet is drawing. Before the pickers are filled — and on a copy of the screen built
    // before they existed — that is the player, exactly as it was.
    Driver ViewedRow() => _browsing ? _viewed : PlayerDriver.Row();

    // Whether the sheet is showing the player's own ride, which is what decides if the player-only blocks
    // (the ledger's career and accolades, fan appeal, the paint and the parts) are theirs to fill.
    bool ViewingPlayer(Driver row)
    {
        if (!_browsing) return true;
        int mine = PlayerDriver.CarNumber;
        return row != null && mine > 0 && row.CarNumber == mine;
    }

    void Update()
    {
        var kb = Keyboard.current;
        if ((kb != null && (kb.escapeKey.wasPressedThisFrame || kb.backspaceKey.wasPressedThisFrame)) ||
            PadInput.WasPressed(Draftmaster.Controls.PadBindings.Back))
        {
            // With a picker's list open, Esc / Back closes the list, not the laptop. TMP keeps IsExpanded
            // true through the list's fade-out, so this holds whether the UI module's own cancel ran first.
            if (CloseOpenPicker()) return;
            Back();
        }
        StepFocusedPicker(kb);
    }

    bool CloseOpenPicker()
    {
        bool closed = false;
        foreach (var picker in new[] { seriesDropdown, driverDropdown })
        {
            if (picker == null || !picker.IsExpanded) continue;
            picker.Hide();
            closed = true;
        }
        return closed;
    }

    // Up / Down on a focused, closed picker steps it to the previous / next option, wrapping round, the way a
    // select box does on a PC — held, it repeats. The pickers' navigation is horizontal only (see
    // KeepArrowsForStepping), so the same keys don't also move focus off them. An open list is left to its
    // own arrow handling: focus is on its items then, not on the picker.
    const float StepRepeatDelay = 0.35f, StepRepeatInterval = 0.07f;
    float _nextStep;

    void StepFocusedPicker(Keyboard kb)
    {
        if (kb == null || EventSystem.current == null) return;
        var focused = EventSystem.current.currentSelectedGameObject;
        TMP_Dropdown picker = null;
        if (seriesDropdown != null && focused == seriesDropdown.gameObject) picker = seriesDropdown;
        else if (driverDropdown != null && focused == driverDropdown.gameObject) picker = driverDropdown;
        if (picker == null || picker.IsExpanded || !picker.interactable || picker.options.Count < 2) return;

        int dir = kb.downArrowKey.isPressed ? 1 : kb.upArrowKey.isPressed ? -1 : 0;
        if (dir == 0) return;

        bool fresh = kb.downArrowKey.wasPressedThisFrame || kb.upArrowKey.wasPressedThisFrame;
        if (fresh) _nextStep = Time.unscaledTime + StepRepeatDelay;
        else if (Time.unscaledTime >= _nextStep) _nextStep = Time.unscaledTime + StepRepeatInterval;
        else return;

        int count = picker.options.Count;
        picker.value = (picker.value + dir + count) % count;   // fires OnSeriesPicked / OnDriverPicked
    }

    // Automatic navigation would send Up / Down from a picker to whatever selectable lies above or below it;
    // horizontal-only keeps Left / Right moving between the pickers and the close box and leaves Up / Down to
    // StepFocusedPicker.
    static void KeepArrowsForStepping(Selectable picker)
    {
        if (picker == null) return;
        var nav = picker.navigation;
        nav.mode = Navigation.Mode.Horizontal;
        picker.navigation = nav;
    }

    // ------------------------------------------------------------------ content

    public void Refresh()
    {
        var theme = PixelUITheme.Instance;

        // One lookup for the whole sheet: the driver the top bar is pointed at, which starts out as the
        // Drivers row behind the number the player races.
        var row = ViewedRow();
        bool mine = ViewingPlayer(row);

        int number = row != null ? row.CarNumber : (mine ? PlayerDriver.CarNumber : 0);
        // #0 is a real number (Sheldon Creed's Xfinity car), so "has a car" is having a row, not number > 0.
        bool hasCar = row != null || number > 0;
        FillCar(mine, hasCar, number);
        // Only the player's own name is overridden by their career name; a rival keeps theirs.
        if (driverName != null)
            FitName(driverName, mine ? PlayerDriver.DisplayName(row) : FullName(row));
        FillAge(theme, row);

        int starts = PlayerStatsLedger.Get("starts");
        int wins = PlayerStatsLedger.Get("wins");
        int top10s = PlayerStatsLedger.Get("top10s");
        int top5s = PlayerStatsLedger.Get("top5s");

        var browsing = BrowsedSeries();
        var record = default(Draftmaster.Weekend.SeriesCareers2025.Record);
        bool real = !mine && SeriesCareers.TryGet(row, browsing, out record);
        // A real driver who had not started a race in this series before 2026 (Layne Riggs in the Cup) reads
        // as a clean sheet, not as unrecorded.
        if (!real && !mine && IsRealDriver(row))
        {
            record = new Draftmaster.Weekend.SeriesCareers2025.Record(0, 0, 0, 0, null);
            real = true;
        }
        if (real) FillCareer(browsing, record);
        else FillCareer(mine, starts, wins, top10s);
        if (real) FillAccolades(theme, browsing, record);
        else FillAccolades(theme, mine, starts, wins, top5s, top10s);
        FillDriverStats(theme, row, mine);
        string shownName = mine ? PlayerDriver.DisplayName(row) : FullName(row);
        FillTraits(theme, shownName);
        FillRelationship(theme, mine, row != null ? shownName : null);

        // The player's fan appeal is the meter this game keeps; a rival's standing with the crowd is the
        // Fan Support their row is rated on, put on the same 0-100 scale.
        float appeal = mine ? FanAppeal.Value
                            : (row != null ? row.FanSupport * 100f / Driver.StatMax : 0f);
        SetBar(xpBar, appeal / 100f);
        if (xpLabel != null) xpLabel.text = Mathf.RoundToInt(appeal) + "/100";
    }

    // The car the viewed driver races. The player's is rendered from their saved scheme and placed sponsor
    // decals, so the sheet shows the car they will actually drive; anyone else wears their number in their
    // championship's carset. A number nobody has painted keeps the slot's caption instead of a blank box.
    void FillCar(bool mine, bool hasCar, int number)
    {
        Sprite sprite = null;
        if (hasCar)
        {
            if (mine) sprite = PaintShop.RenderPlayerCar();
            if (sprite == null) sprite = Resources.Load<Sprite>(CarsetOf(_fieldSeries) + "livery" + number);
        }

        if (carImage != null)
        {
            carImage.sprite = sprite;
            carImage.enabled = sprite != null;
            if (sprite != null)
            {
                // Whole-pixel scale only, so the car stays as crisp as it is on track.
                var slot = carImage.rectTransform.parent as RectTransform;
                float w = sprite.rect.width, h = sprite.rect.height;
                float room = slot != null ? Mathf.Min((slot.rect.width - 8f) / w, (slot.rect.height - 8f) / h) : 1f;
                float scale = Mathf.Max(1f, Mathf.Floor(room));
                carImage.rectTransform.sizeDelta = new Vector2(w * scale, h * scale);
            }
        }

        if (carSlotCaption != null)
        {
            carSlotCaption.gameObject.SetActive(sprite == null);
            carSlotCaption.text = hasCar ? $"[ No paint for #{number} ]" : "[ No car ]";
        }
    }

    // The carset a championship's cars are painted in — the same three GridSpawner puts on track.
    static string CarsetOf(SeriesInfo series)
    {
        if (SimulatedField.TryRacingSeries(series, out var racing))
            return racing == Draftmaster.Weekend.RacingSeries.Trucks ? "cts25" : "xfi25";
        return CupRoster2026.CarsetPrefix;
    }

    // Which of the three championships the top bar is browsing; the seeded Drivers field is the Cup.
    Draftmaster.Weekend.RacingSeries BrowsedSeries() =>
        SimulatedField.TryRacingSeries(_fieldSeries, out var racing) ? racing : Draftmaster.Weekend.RacingSeries.Cup;

    static bool IsRealDriver(Driver row)
    {
        foreach (Draftmaster.Weekend.RacingSeries series in System.Enum.GetValues(typeof(Draftmaster.Weekend.RacingSeries)))
            if (SeriesCareers.TryGet(row, series, out _)) return true;
        return false;
    }

    static string SeriesWord(Draftmaster.Weekend.RacingSeries series) => series switch
    {
        Draftmaster.Weekend.RacingSeries.National => "Xfinity",
        Draftmaster.Weekend.RacingSeries.Trucks => "Truck",
        _ => "Cup",
    };

    // The ledger counts the player's races and nobody else's. A rival with no real Cup career on file reads
    // as unrecorded rather than being handed the player's numbers.
    void FillCareer(bool mine, int starts, int wins, int top10s)
    {
        SetPair(careerRows, 0, "Starts", mine ? starts.ToString() : "—");
        SetPair(careerRows, 1, "Wins", mine ? wins.ToString() : "—");
        SetPair(careerRows, 2, "Top 10s", mine ? top10s.ToString() : "—");
    }

    // A real driver's real career in this series, to the end of 2025.
    void FillCareer(Draftmaster.Weekend.RacingSeries series, Draftmaster.Weekend.SeriesCareers2025.Record record)
    {
        SetPair(careerRows, 0, SeriesWord(series) + " Starts", record.Starts.ToString());
        SetPair(careerRows, 1, "Wins", record.Wins.ToString());
        SetPair(careerRows, 2, "Top 10s", record.Top10s.ToString());
    }

    // The honours a real driver's record in this series carries; titles in gold. Lines are kept to the 17
    // characters the column takes; the series they were won in is the one the top bar is showing.
    void FillAccolades(PixelUITheme theme, Draftmaster.Weekend.RacingSeries series,
                       Draftmaster.Weekend.SeriesCareers2025.Record record)
    {
        var lines = new List<(string text, bool gold)>();
        if (record.Titles == 1) lines.Add(($"Champion {record.TitleYears[0]}", true));
        else if (record.Titles > 1) lines.Add(($"{record.Titles}× Champion", true));
        if (record.Poles > 0) lines.Add(($"{record.Poles} Pole{(record.Poles == 1 ? "" : "s")}", false));
        lines.Add((record.Starts > 0 ? "Record to 2025" : "No starts yet", false));
        ShowAccolades(theme, lines);
    }

    // Every line here is something the ledger can prove. Nothing earned yet says so plainly.
    void FillAccolades(PixelUITheme theme, bool mine, int starts, int wins, int top5s, int top10s)
    {
        var lines = new List<(string text, bool gold)>();
        if (!mine)
        {
            // Nothing in the ledger is about this driver, and the database keeps no honours roll yet.
            lines.Add(("No record on file", false));
        }
        else
        {
            if (wins > 0) lines.Add(($"{wins} Race Win{(wins == 1 ? "" : "s")}", true));
            if (top5s > 0) lines.Add(($"{top5s} Top Five{(top5s == 1 ? "" : "s")}", true));
            if (PlayerStatsLedger.Get("fights.won") > 0)
                lines.Add(($"{PlayerStatsLedger.Get("fights.won")}× Scraps Won", false));
            if (PlayerStatsLedger.Get("locations") > 0)
                lines.Add(($"{PlayerStatsLedger.Get("locations")} Places Seen", false));
            if (lines.Count == 0)
                lines.Add((starts > 0 ? "Nothing yet" : "No starts yet", false));
        }

        ShowAccolades(theme, lines);
    }

    void ShowAccolades(PixelUITheme theme, List<(string text, bool gold)> lines)
    {
        for (int i = 0; i < accoladeLines.Count; i++)
        {
            var label = accoladeLines[i];
            if (label == null) continue;
            if (i < lines.Count)
            {
                label.text = lines[i].text;
                if (theme != null) label.color = lines[i].gold ? theme.gold : theme.textDim;
                label.gameObject.SetActive(true);
            }
            else label.gameObject.SetActive(false);
        }
    }

    // The Name value shares its line with a label in a column only as wide as the car, so a full name often
    // will not fit: "Ace Emerson" becomes "A. Emerson", then "Emerson", and anything still too long is clipped
    // by the box (the pixel faces have no ellipsis glyph).
    static void FitName(TextMeshProUGUI box, string name)
    {
        box.text = name;
        float room = box.rectTransform.rect.width;
        if (room <= 0f || box.GetPreferredValues(name).x <= room) return;

        int space = name.IndexOf(' ');
        if (space <= 0 || space >= name.Length - 1) return;
        string surname = name.Substring(space + 1);
        string initialled = name[0] + ". " + surname;
        box.text = box.GetPreferredValues(initialled).x <= room ? initialled : surname;
    }

    void FillAge(PixelUITheme theme, Driver row)
    {
        if (driverAge == null) return;
        bool known = row != null && row.Age > 0;
        driverAge.text = known ? row.Age.ToString() : "—";
        if (theme != null) driverAge.color = known ? theme.text : theme.textDisabled;
    }

    // Every attribute the Drivers table rates this driver on, in DriverAttributeSheet order — the same
    // order the builder laid the rows out in. A save with no row at all reads as unrated rather than
    // drawing eighteen empty bars.
    //
    // A rival's stats are only on show once scouted (ScoutingLedger): racing their series or watching it
    // uncovers a few a session. The rest read "??" with an empty bar, and the heading's line says how far
    // the scouting has got.
    void FillDriverStats(PixelUITheme theme, Driver row, bool mine)
    {
        var sheet = DriverAttributeSheet.All;
        for (int i = 0; i < driverStats.Count && i < sheet.Length; i++)
        {
            var attribute = sheet[i];
            bool known = row == null || ScoutingLedger.IsKnown(row, i, mine);
            int value = row != null && known ? attribute.Read(row) : -1;
            SetStat(driverStats, i, attribute.Name,
                    value >= 0 ? value / (float)Mathf.Max(1, attribute.Max) : 0f,
                    value >= 0 ? value.ToString() : known ? "—" : "??");
            if (theme != null && driverStats[i].value != null)
                driverStats[i].value.color = value >= 0 ? theme.text : theme.textDisabled;
        }

        if (scoutingLabel == null) return;
        if (row != null && !mine)
        {
            int seen = ScoutingLedger.KnownCount(row, false);
            int total = ScoutingLedger.Total;
            scoutingLabel.text = seen >= total ? "Fully scouted" : $"Scouted {seen} of {total}";
        }
        else scoutingLabel.text = "";
    }

    void FillTraits(PixelUITheme theme, string name)
    {
        var traits = DriverTraits.For(name);
        for (int i = 0; i < traitLines.Count; i++)
        {
            var line = traitLines[i];
            if (line == null) continue;
            if (i < traits.Count)
            {
                line.text = DriverTraits.Label(traits[i]);
                if (theme != null) line.color = theme.text;
            }
            else if (i == 0 && traits.Count == 0)
            {
                line.text = "None known";
                if (theme != null) line.color = theme.textDisabled;
            }
            else line.text = "";
        }
    }

    // The rivalry score between this driver and the player, as the racing keeps it — keyed by the name the
    // player's car carries on track, which is their career name.
    void FillRelationship(PixelUITheme theme, bool mine, string name)
    {
        bool known = !mine && !string.IsNullOrEmpty(name);
        float score = known ? DriverRelationships.Get(PlayerDriver.DisplayName(PlayerDriver.Row()), name) : 0f;
        var standing = DriverRelationships.StandingOf(score);

        for (int i = 0; i < relationshipRows.Count; i++)
        {
            var pair = relationshipRows[i];
            // The player's own sheet: N/A straight under the heading, where the standing would be.
            if (pair.label != null)
            {
                pair.label.text = mine ? (i == 0 ? "N/A" : "") : !known ? "" : i == 0 ? "Standing" : "Score";
                if (theme != null) pair.label.color = mine ? theme.text : theme.textDim;
            }
            if (pair.value == null) continue;
            pair.value.text = !known ? "" : i == 0 ? standing.ToString()
                                                   : (score > 0f ? "+" : "") + Mathf.RoundToInt(score);
            if (theme != null && i == 0)
                pair.value.color = standing == DriverRelationships.Standing.Ally ? theme.confirm
                                 : standing == DriverRelationships.Standing.Neutral ? theme.text : theme.danger;
        }

        if (relationshipNote == null) return;
        relationshipNote.text = !known ? "" : standing switch
        {
            DriverRelationships.Standing.Ally => "Friendly. Will work with you in the draft.",
            DriverRelationships.Standing.Rival => "A declared rivalry. Expect no favours.",
            DriverRelationships.Standing.Furious => "Out for payback. Watch your mirrors.",
            _ => score == 0f ? "No history between you yet." : "Nothing either way.",
        };
        if (theme != null) relationshipNote.color = theme.textDim;
    }

    // ------------------------------------------------------------------ helpers

    // A driver's name as their own row has it, with the timing-tower short name as the fallback. Used for
    // everyone except the player, whose career name is allowed to sit over the seat they took.
    static string FullName(Driver row)
    {
        if (row == null) return "No driver";
        string full = ((row.FirstName ?? "") + " " + (row.LastName ?? "")).Trim();
        if (full.Length > 0) return full;
        string label = RosterLookup.LabelName(row);
        return label.Length > 0 ? label : "No driver";
    }

    void SetStat(List<StatRow> rows, int index, string label, float fill01, string value)
    {
        if (index < 0 || index >= rows.Count) return;
        var row = rows[index];
        if (row.label != null) row.label.text = label;
        if (row.value != null) row.value.text = value;
        if (row.cells != null)
            IronOvalUI.SetCells(row.cells, Mathf.RoundToInt(Mathf.Clamp01(fill01) * 10f), 10, row.tint);
    }

    static void SetPair(List<TextPair> rows, int index, string label, string value)
    {
        if (index < 0 || index >= rows.Count) return;
        if (rows[index].label != null) rows[index].label.text = label;
        if (rows[index].value != null) rows[index].value.text = value;
    }

    static void SetBar(RectTransform fill, float amount01)
    {
        if (fill == null || fill.parent is not RectTransform track) return;
        fill.sizeDelta = new Vector2(Mathf.Round(track.rect.width * Mathf.Clamp01(amount01)), fill.sizeDelta.y);
    }

    // ------------------------------------------------------------------ the close button (wired by the builder)

    // Back to wherever the sheet was opened from — the RV or the factory when a laptop opened it, the
    // title when it was opened cold. GarageScreenLoader owns that memory; titleSceneName is the fallback
    // it falls through to, so the field still says where "nowhere to go back to" leads.
    public void Back()
    {
        if (!GarageScreenLoader.Leave(titleSceneName))
            Debug.LogWarning($"GarageScreenUI: {titleSceneName} isn't in the build settings, so the X has nowhere to go.");
    }
