using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using TMPro;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;
using UnityEngine.UI;

// Finds text authored in all caps, against the letter-case rule (Docs/Type-Scale.md, "Letter case": Title
// Case for labels, sentence case for sentences, capitals only for acronyms). Every uGUI Text and TMP text in
// the prefabs the build reaches and the demo scenes goes into Docs/LetterCaseAudit.md with its Title Case
// form beside it.
//
// It reads, it does not fix: whether a line is a label or a sentence, and whether "WATKINS GLEN" in the
// middle of one is a name, wants a person. Text written in code is not here — it is cased in the source.
// A box whose text is filled at runtime shows its authored placeholder, which is worth fixing anyway: it is
// what the editor shows and what a frame shows before the binder runs.
public static class LetterCaseAudit
{
    const string ReportPath = "Docs/LetterCaseAudit.md";

    static readonly string[] ThirdParty = { "Assets/Ink/", "Assets/PlayFab", "Assets/TextMesh Pro/", "Assets/Plugins/" };

    struct Finding
    {
        public string asset, path, text, suggested;
    }

    [MenuItem("Draftmaster/UI/Audit Letter Case", false, 73)]
    public static void Run()
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode)
        {
            Debug.LogWarning("[LetterCaseAudit] Leave Play Mode first — it opens scenes.");
            return;
        }

        var findings = new List<Finding>();
        int prefabs = 0;
        var shipped = ButtonAudit.Shipped();

        foreach (var guid in AssetDatabase.FindAssets("t:Prefab", new[] { "Assets" }))
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            if (ThirdParty.Any(p => path.StartsWith(p, System.StringComparison.OrdinalIgnoreCase))) continue;
            if (!shipped.Contains(path)) continue;
            var root = AssetDatabase.LoadAssetAtPath<GameObject>(path);
            if (root == null) continue;
            prefabs++;
            Collect(root, path, findings);
        }

        var opened = new List<Scene>();
        foreach (var scenePath in ButtonAudit.DemoScenes)
        {
            var scene = SceneManager.GetSceneByPath(scenePath);
            if (!scene.IsValid() || !scene.isLoaded)
            {
                if (!File.Exists(scenePath)) continue;
                scene = EditorSceneManager.OpenScene(scenePath, OpenSceneMode.Additive);
                opened.Add(scene);
            }
            foreach (var go in scene.GetRootGameObjects()) Collect(go, scenePath, findings);
        }
        foreach (var scene in opened) EditorSceneManager.CloseScene(scene, true);

        Write(findings, prefabs);
        Debug.Log($"[LetterCaseAudit] {findings.Count} all-caps text(s) across {prefabs} prefabs and the demo scenes — {ReportPath}");
    }

    static void Collect(GameObject root, string asset, List<Finding> into)
    {
        foreach (var t in root.GetComponentsInChildren<Text>(true)) Check(t.text, t.transform, root.transform, asset, into);
        foreach (var t in root.GetComponentsInChildren<TMP_Text>(true)) Check(t.text, t.transform, root.transform, asset, into);
    }

    static void Check(string text, Transform t, Transform root, string asset, List<Finding> into)
    {
        if (!IsAllCaps(text)) return;
        string suggested = Draftmaster.Controls.UIText.TitleCase(text);
        if (suggested == text) return;   // an acronym on its own ("DNF", "XP")
        into.Add(new Finding { asset = asset, path = PathOf(t, root), text = text, suggested = suggested });
    }

    // Two or more capital letters and no lower-case one.
    static bool IsAllCaps(string text)
    {
        if (string.IsNullOrEmpty(text)) return false;
        int caps = 0;
        foreach (char c in text)
        {
            if (!char.IsLetter(c)) continue;
            if (char.IsLower(c)) return false;
            caps++;
        }
        return caps >= 2;
    }

    static string PathOf(Transform t, Transform root)
    {
        var parts = new List<string>();
        for (var p = t; p != null; p = p.parent)
        {
            parts.Add(p.name);
            if (p == root) break;
        }
        parts.Reverse();
        return string.Join("/", parts);
    }

    static string Cell(string s) => s.Replace("|", "\\|").Replace("\n", " ").Replace("\r", "");

    static void Write(List<Finding> findings, int prefabs)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Letter case audit");
        sb.AppendLine();
        sb.AppendLine("Generated by `Draftmaster > UI > Audit Letter Case` (`Assets/Editor/LetterCaseAudit.cs`). Every uGUI and");
        sb.AppendLine($"TMP text authored in all caps in the {prefabs} prefabs the build reaches and the demo scenes. The rule is");
        sb.AppendLine("in `Docs/Type-Scale.md` (\"Letter case\"): Title Case for labels, sentence case for sentences. The suggestion");
        sb.AppendLine("column is the Title Case form — a sentence wants sentence case instead.");
        sb.AppendLine();
        sb.AppendLine("| Asset | Text object | Authored | Title Case |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var f in findings.OrderBy(f => f.asset).ThenBy(f => f.path))
            sb.AppendLine($"| {f.asset} | {Cell(f.path)} | {Cell(f.text)} | {Cell(f.suggested)} |");
        Directory.CreateDirectory(Path.GetDirectoryName(ReportPath));
        File.WriteAllText(ReportPath, sb.ToString());
    }
}
